import fs from 'node:fs/promises';
import path from 'node:path';

const projectRoot = process.cwd();
const sourceHtmlPath = path.join(projectRoot, 'dist', 'index.html');
const outputDirectory = path.join(projectRoot, 'src', 'native', 'generated');
const outputFilePath = path.join(outputDirectory, 'webAppHtml.ts');

async function main() {
  const html = await fs.readFile(sourceHtmlPath, 'utf8');
  const serializedHtml = JSON.stringify(html);
  const fileContents = `// Auto-generated by scripts/generate-webview-html.mjs\n// Do not edit this file by hand.\n\nexport const webAppHtml = ${serializedHtml};\n`;

  await fs.mkdir(outputDirectory, { recursive: true });
  await fs.writeFile(outputFilePath, fileContents, 'utf8');

  console.log(`Embedded web bundle generated at ${path.relative(projectRoot, outputFilePath)}`);
}

main().catch((error) => {
  console.error('Failed to embed Vite build into Expo WebView:', error);
  process.exit(1);
});
